#!/usr/bin/env python3
"""Generate docs/configuration.md from the Pydantic config model and config.example.toml.

    uv run python scripts/gen_config_doc.py           rewrite docs/configuration.md
    uv run python scripts/gen_config_doc.py --check   exit 1 when docs/configuration.md is out of date

Sources, in this order of trust:
- src/jarvis/config.py: every section and key, its type, constraints and default (from the model itself);
  the class docstring is the section's introduction; a field's own comments are its meaning when
  config.example.toml has none.
- config.example.toml: the comments next to each key (the line above it and the end of its line), the
  comment block that opens a section, and the value it sets when that differs from the model default.
Nothing else is written: a key without a comment gets no description.
"""

from __future__ import annotations

import argparse
import ast
import io
import json
import re
import sys
import tokenize
import tomllib
import types
import typing
from dataclasses import dataclass, field
from pathlib import Path

import annotated_types
from pydantic import BaseModel
from pydantic_core import PydanticUndefined

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from jarvis import config as config_module  # noqa: E402

CONFIG_SOURCE = REPO / "src" / "jarvis" / "config.py"
EXAMPLE_FILE = REPO / "config.example.toml"
OUTPUT_FILE = REPO / "docs" / "configuration.md"

HEADER = """\
# Configuration reference

<!-- Generated by scripts/gen_config_doc.py from src/jarvis/config.py and config.example.toml.
     Do not edit by hand: run `uv run python scripts/gen_config_doc.py` after changing either file. -->

This page lists every setting in `config.toml`: its type, its default and what it does. It is generated
from the configuration model in `src/jarvis/config.py` and the comments in `config.example.toml`.

- **`config.toml`** is your configuration, in the Jarvis folder. `jarvis setup` creates it from
  `config.example.toml` (with the comments) and, when it already exists, only adds the keys it lacks.
  The file is personal and ignored by git.
- **`config.local.toml`** is optional and sits next to `config.toml`. It is merged over `config.toml` when
  Jarvis loads: tables merge key by key; every other value, arrays and arrays of tables included, replaces
  the value from `config.toml`. Use it for values that should stay out of a shared `config.toml`.
- **Secrets never go into a config file.** API keys and tokens live in the macOS Keychain
  (`jarvis key set NAME`).
- **Default** is the value Jarvis uses when the key is missing. **Example** is the value that
  `config.example.toml` (and so a new `config.toml`) sets, shown only when it differs from the default.
  A key marked *required* has no default and must be present.
- Unknown keys are an error, so a typo is reported instead of being ignored. `jarvis doctor` checks the file.
"""


# --------------------------------------------------------------------------- comments in config.py


def source_comments(source: str) -> tuple[dict[tuple[str, str], str], dict[str, str]]:
    """{(class name, field name): comment} from the comment lines right above a field and the comment at
    the end of its line; and {class name: docstring}."""
    comments: dict[int, tuple[str, bool]] = {}  # line -> (text, whole line is a comment)
    lines = source.splitlines()
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            row = tok.start[0]
            own_line = not lines[row - 1][: tok.start[1]].strip()
            comments[row] = (tok.string.lstrip("#").strip(), own_line)
    fields: dict[tuple[str, str], str] = {}
    docs: dict[str, str] = {}
    for node in ast.parse(source).body:
        if not isinstance(node, ast.ClassDef):
            continue
        doc = ast.get_docstring(node)
        if doc:
            docs[node.name] = " ".join(doc.split())
        for stmt in node.body:
            if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
                continue
            above: list[str] = []
            row = stmt.lineno - 1
            while row in comments and comments[row][1]:
                above.insert(0, comments[row][0])
                row -= 1
            inline = [comments[r][0] for r in range(stmt.lineno, (stmt.end_lineno or stmt.lineno) + 1) if r in comments]
            text = " ".join(part for part in [*above, *inline] if part)
            if text:
                fields[(node.name, stmt.target.id)] = text
    return fields, docs


# --------------------------------------------------------------------------- comments in config.example.toml

_HEADER_RE = re.compile(r"^\s*(\[\[?)\s*([^\]]+?)\s*\]\]?\s*(#.*)?$")
_KEY_RE = re.compile(r"^\s*([A-Za-z0-9_-]+)\s*=")


def _is_toml(text: str) -> bool:
    """A commented-out setting (`# name = "x"`, `# [[shortcuts.allowed]]`) rather than prose."""
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return False
    return bool(text.strip())


def _split_comment(line: str) -> tuple[str, str]:
    """(code, comment) of one TOML line, a `#` inside a string not counting."""
    quote = ""
    for i, ch in enumerate(line):
        if quote:
            if ch == "\\" and quote == '"':
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i], line[i + 1 :].strip()
    return line, ""


def _bracket_depth(code: str) -> int:
    depth, quote = 0, ""
    for ch in code:
        if quote:
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
    return depth


@dataclass
class ExampleNotes:
    keys: dict[tuple[str, ...], str] = field(default_factory=dict)  # dotted key path -> comment
    sections: dict[tuple[str, ...], str] = field(default_factory=dict)  # table path -> its opening comment block


def example_notes(text: str) -> ExampleNotes:
    """The comments of config.example.toml, attached the way a reader sees them: the comment block that
    opens a table belongs to the table; any later block directly above a key, plus the comment at the end
    of the key's line and the indented comment lines under it, belongs to that key; a block directly above
    a `[table]` header (not `[[array]]`) belongs to that table's key."""
    notes = ExampleNotes()
    table: tuple[str, ...] = ()
    block: list[str] = []  # comment lines since the last blank or code line
    opening = False  # still before the first key of the current table
    last_key: tuple[str, ...] | None = None  # for indented continuation comments
    depth = 0  # inside a multi-line array
    for raw in text.splitlines():
        if depth > 0:
            depth += _bracket_depth(_split_comment(raw)[0])
            continue
        stripped = raw.strip()
        if not stripped:
            if opening and block:
                notes.sections[table] = _join(block)
                opening = False
            block, last_key = [], None
            continue
        if stripped.startswith("#"):
            comment = stripped.lstrip("#").strip()
            if last_key is not None and raw[:1].isspace():
                notes.keys[last_key] = _join([notes.keys.get(last_key, ""), comment])
            else:
                last_key = None
                block.append(comment)
            continue
        header = _HEADER_RE.match(raw)
        if header and not _KEY_RE.match(raw):
            path = tuple(part.strip().strip('"') for part in header.group(2).split("."))
            if opening and block:
                notes.sections[table] = _join(block)
            elif block and header.group(1) == "[":
                notes.keys[path] = _join(block)
            table, block, opening, last_key = path, [], True, None
            continue
        key = _KEY_RE.match(raw)
        code, comment = _split_comment(raw)
        if key:
            path = (*table, key.group(1))
            if opening and block:
                notes.sections[table] = _join(block)
            elif block:
                notes.keys[path] = _join(block)
            if comment:
                notes.keys[path] = _join([notes.keys.get(path, ""), comment])
            last_key = path
        else:
            last_key = None
        opening, block = False, []
        depth = max(_bracket_depth(code), 0)
    return notes


def _join(lines: list[str]) -> str:
    """One paragraph from comment lines. A commented-out setting is kept as code when the block also has
    prose (an example under its explanation) and dropped when the block is nothing but settings."""
    lines = [" ".join(line.split()) for line in lines if line.strip()]
    if all(_is_toml(line) for line in lines):
        return ""
    return " ".join(code(line) if _is_toml(line) else line for line in lines)


# --------------------------------------------------------------------------- rendering


def toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, BaseModel):
        value = value.model_dump()
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = []
        for k, v in value.items():
            name = k if re.fullmatch(r"[A-Za-z0-9_-]+", k) else json.dumps(k, ensure_ascii=False)
            items.append(f"{name} = {toml_value(v)}")
        return "{ " + ", ".join(items) + " }"
    return json.dumps(value, ensure_ascii=False)


def code(text: str) -> str:
    fence = "``" if "`" in text else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def prose(text: str) -> str:
    """Comment text as Markdown: `<` outside code spans is escaped so `<name>` is not taken for HTML."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;") for p in parts).strip()


def _model_of(annotation: object) -> type[BaseModel] | None:
    return annotation if isinstance(annotation, type) and issubclass(annotation, BaseModel) else None


def type_name(annotation: object, plural: bool = False) -> str:
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin is typing.Literal:
        return code(" | ".join(json.dumps(a, ensure_ascii=False) for a in args))
    if origin in (typing.Union, types.UnionType):
        return " or ".join(type_name(a, plural) for a in args)
    if origin is list:
        return "list of " + type_name(args[0], plural=True)
    if origin is dict:
        return "table of " + type_name(args[1], plural=True)
    names = {bool: "boolean", int: "integer", float: "number", str: "string"}
    if annotation in names:
        name = names[annotation]
        return name + "s" if plural else name
    if _model_of(annotation):
        return "tables" if plural else "table"
    return str(annotation)


def constraints(info) -> str:
    bounds = {type(item).__name__: item for item in info.metadata}
    if "Ge" in bounds and "Le" in bounds:
        parts = [f"{bounds['Ge'].ge} to {bounds['Le'].le}"]
        metadata = [m for m in info.metadata if not isinstance(m, (annotated_types.Ge, annotated_types.Le))]
    else:
        parts, metadata = [], info.metadata
    for item in metadata:
        if isinstance(item, annotated_types.Ge):
            parts.append(f">= {item.ge}")
        elif isinstance(item, annotated_types.Gt):
            parts.append(f"> {item.gt}")
        elif isinstance(item, annotated_types.Le):
            parts.append(f"<= {item.le}")
        elif isinstance(item, annotated_types.Lt):
            parts.append(f"< {item.lt}")
        elif isinstance(item, annotated_types.MinLen):
            parts.append(f"at least {item.min_length} {'entry' if item.min_length == 1 else 'entries'}")
        elif isinstance(item, annotated_types.MaxLen):
            parts.append(f"at most {item.max_length} characters")
    if typing.get_origin(info.annotation) is not list:
        parts = [p.replace("entry", "character").replace("entries", "characters") for p in parts]
    return ", ".join(parts)


def default_of(info) -> object:
    if info.default_factory is not None:
        return info.default_factory()
    return info.default


def deprecated_fields(model: type[BaseModel]) -> dict[str, str]:
    """{field: what replaces it}, read from the model's own `deprecated_keys` property: a field is
    deprecated when setting it alone makes that property name it."""
    prop = getattr(model, "deprecated_keys", None)
    if not isinstance(prop, property):
        return {}
    found = {}
    for name, info in model.model_fields.items():
        if info.annotation is not str or info.is_required():
            continue
        try:
            messages = model.model_validate({name: "x"}).deprecated_keys
        except Exception:
            continue
        for message in messages:
            if re.search(rf"\b{re.escape(name)}\b", message):
                hint = re.search(r"\(use ([^)]*)\)", message)
                found[name] = hint.group(1) if hint else ""
    return found


@dataclass
class Section:
    path: tuple[str, ...]
    model: type[BaseModel]
    kind: str  # "table", "array" ([[...]]), "map" (a table of tables keyed by a name)
    example: object  # the section's value in config.example.toml (dict, list or None)


def walk(model: type[BaseModel], path: tuple[str, ...], kind: str, example: object, out: list[Section]) -> None:
    out.append(Section(path, model, kind, example))
    sample = _first_entry(example, kind)
    for name, info in model.model_fields.items():
        nested = _model_of(info.annotation)
        origin, args = typing.get_origin(info.annotation), typing.get_args(info.annotation)
        sub = sample.get(name) if isinstance(sample, dict) else None
        if nested:
            walk(nested, (*path, name), "table", sub, out)
        elif origin is list and _model_of(args[0]):
            walk(args[0], (*path, name), "array", sub, out)
        elif origin is dict and _model_of(args[1]):
            walk(args[1], (*path, name), "map", sub, out)


def _first_entry(example: object, kind: str) -> object:
    if kind == "array":
        return example[0] if isinstance(example, list) and example else None
    if kind == "map":
        return next(iter(example.values()), None) if isinstance(example, dict) and example else None
    return example


def section_title(section: Section) -> str:
    dotted = ".".join(section.path)
    if section.kind == "array":
        return f"[[{dotted}]]"
    if section.kind == "map":
        return f'[{dotted}."NAME"]'
    return f"[{dotted}]"


def anchor(title: str) -> str:
    """GitHub's heading anchor: lower case, punctuation other than - and _ dropped, spaces as -."""
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def render_key(section: Section, name: str, info, field_notes, notes: ExampleNotes, deprecated: dict[str, str]) -> str:
    path = (*section.path, name)
    facts = [type_name(info.annotation)]
    limits = constraints(info)
    if limits:
        facts[0] += f", {limits}"
    sample = _first_entry(section.example, section.kind)
    has_example = isinstance(sample, dict) and name in sample
    if info.is_required() or default_of(info) is PydanticUndefined:
        facts.append("*required*")
        if has_example:
            facts.append("example: " + code(toml_value(sample[name])))
    else:
        default = default_of(info)
        facts.append("default: " + code(toml_value(default)))
        if has_example and sample[name] != (default.model_dump() if isinstance(default, BaseModel) else default):
            facts.append("example: " + code(toml_value(sample[name])))
    if name in deprecated:
        replacement = " and ".join(code(k.strip()) for k in deprecated[name].split(" and ") if k.strip())
        facts.append(f"**deprecated**, use {replacement} instead" if replacement else "**deprecated**")
    meaning = notes.keys.get(path) if section.kind == "table" else None
    meaning = meaning or field_notes.get((section.model.__name__, name), "")
    if meaning.strip().lower() == "deprecated":
        meaning = ""
    line = f"- **{code(name)}** ({'; '.join(facts)})"
    return line + (f": {prose(meaning)}" if meaning else "")


def render(config_source: str, example_text: str) -> str:
    field_notes, docs = source_comments(config_source)
    notes = example_notes(example_text)
    example = tomllib.loads(example_text)
    sections: list[Section] = []
    for name, info in config_module.Config.model_fields.items():
        walk(_model_of(info.annotation), (name,), "table", example.get(name), sections)

    out = [HEADER, "## Sections", ""]
    top = [s for s in sections if len(s.path) == 1]
    out.append(" · ".join(f"[{code(s.path[0])}](#{anchor(section_title(s))})" for s in top))
    out.append("")
    for section in sections:
        title = section_title(section)
        out.append(f"{'##' if len(section.path) == 1 else '###'} {title}")
        out.append("")
        if section.kind == "array":
            out.append(f"An array of tables: each `{title}` block in the file adds one entry.")
            out.append("")
        elif section.kind == "map":
            out.append(f'A table of tables: each `"NAME" = {{ ... }}` line under `[{".".join(section.path)}]` is one entry.')
            out.append("")
        intro = [
            docs.get(section.model.__name__, ""),
            notes.sections.get(section.path, "") if section.kind == "table" else "",
            notes.keys.get(section.path, ""),
        ]
        parent = sections[[s.path for s in sections].index(section.path[:-1])] if len(section.path) > 1 else None
        if parent is not None:
            intro.append(field_notes.get((parent.model.__name__, section.path[-1]), "") if not intro[0] else "")
        for paragraph in dict.fromkeys(p for p in intro if p):
            out.append(prose(paragraph))
            out.append("")
        deprecated = deprecated_fields(section.model)
        keys = [
            render_key(section, name, info, field_notes, notes, deprecated)
            for name, info in section.model.model_fields.items()
            if not _is_sub_section(info.annotation)
        ]
        subs = [s for s in sections if s.path[:-1] == section.path]
        keys += [f"- **{code(s.path[-1])}**: see [{code(section_title(s))}](#{anchor(section_title(s))})." for s in subs]
        out.extend(keys)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _is_sub_section(annotation: object) -> bool:
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if _model_of(annotation):
        return True
    if origin is list:
        return bool(_model_of(args[0]))
    if origin is dict:
        return bool(_model_of(args[1]))
    return False


def generate() -> str:
    return render(CONFIG_SOURCE.read_text(encoding="utf-8"), EXAMPLE_FILE.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/configuration.md from the config model.")
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/configuration.md is out of date")
    args = parser.parse_args(argv)
    text = generate()
    current = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.is_file() else ""
    if args.check:
        if current != text:
            print("docs/configuration.md is out of date: run `uv run python scripts/gen_config_doc.py`", file=sys.stderr)
            return 1
        print("docs/configuration.md is up to date")
        return 0
    if current != text:
        OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_FILE.write_text(text, encoding="utf-8")
        print("wrote docs/configuration.md")
    else:
        print("docs/configuration.md is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
