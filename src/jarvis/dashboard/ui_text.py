def all_strings() -> dict[str, str]:
    """Name -> text for every UI string (the English-only test and the docs)."""
    return {name: value for name, value in vars(UI).items() if name.isupper() and isinstance(value, str)}


CHANNEL_LABELS = {
    "cli": UI.CHANNEL_CLI,
    None: UI.CHANNEL_CLI,
    "": UI.CHANNEL_CLI,
    "voice": UI.CHANNEL_VOICE,
    "telegram": UI.CHANNEL_TELEGRAM,
    "scheduler": UI.CHANNEL_SCHEDULER,
    "brief": UI.CHANNEL_SCHEDULER,
}


def channel_label(channel: str | None) -> str:
    return CHANNEL_LABELS.get(channel, (channel or "").capitalize() or UI.CHANNEL_CLI)
